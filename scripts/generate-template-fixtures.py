#!/usr/bin/env python3
"""Generates OMNIATests/TemplateFixtures.swift: each catalog model's chat template plus the text
Hugging Face Transformers' renderer (Python Jinja2) produces for three conversations. The Swift
tests render the same conversations with swift-jinja and must produce identical text.

Usage:
    node scripts/read-gguf-headers.mjs scripts/catalog/models.json /tmp/omnia-headers
    python3 -m pip install jinja2
    python3 scripts/generate-template-fixtures.py /tmp/omnia-headers OMNIATests/TemplateFixtures.swift
"""
import json
import re
import sys
from datetime import datetime
from pathlib import Path

import jinja2
from jinja2.ext import Extension, loopcontrols
from jinja2.sandbox import ImmutableSandboxedEnvironment

FIXED_DATE = datetime(2026, 11, 3, 12, 0)


class GenerationExtension(Extension):
    """Transformers' {% generation %} block (assistant-mask tracking): renders its body."""
    tags = {"generation"}

    def parse(self, parser):
        lineno = next(parser.stream).lineno
        body = parser.parse_statements(("name:endgeneration",), drop_needle=True)
        return jinja2.nodes.CallBlock(self.call_method("_render"), [], [], body).set_lineno(lineno)

    def _render(self, caller):
        return caller()


def raise_exception(message):
    raise jinja2.exceptions.TemplateError(message)


def tojson(value, ensure_ascii=False, indent=None, separators=None, sort_keys=False):
    return json.dumps(value, ensure_ascii=ensure_ascii, indent=indent, separators=separators, sort_keys=sort_keys)


ENV = ImmutableSandboxedEnvironment(trim_blocks=True, lstrip_blocks=True,
                                    extensions=[loopcontrols, GenerationExtension])
ENV.filters["tojson"] = tojson
ENV.globals["raise_exception"] = raise_exception
ENV.globals["strftime_now"] = lambda fmt: FIXED_DATE.strftime(fmt)

# Must match ToolDefinition.declaration / ToolDefinition.schema in Swift (same key order).
TOOLS = [
    {"type": "function", "function": {
        "name": "calculator",
        "description": "Evaluates an arithmetic expression.",
        "parameters": {"type": "object",
                       "properties": {"expression": {"type": "string", "description": "The expression, e.g. 2*(3+4)"}},
                       "required": ["expression"]}}},
    {"type": "function", "function": {
        "name": "web_search",
        "description": "Searches the web.",
        "parameters": {"type": "object",
                       "properties": {"query": {"type": "string", "description": "Search terms"},
                                      "count": {"type": "integer", "description": "Number of results"}},
                       "required": ["query"]}}},
]

SYSTEM = {"role": "system", "content": "You are helpful."}
SCENARIOS = {
    "chat": ([SYSTEM,
              {"role": "user", "content": "Hello!"},
              {"role": "assistant", "content": "Hi! How can I help?"},
              {"role": "user", "content": "Tell me a joke."}], None),
    "toolPrompt": ([SYSTEM, {"role": "user", "content": "What is 17 * 23?"}], TOOLS),
    "toolRoundTrip": ([SYSTEM,
                       {"role": "user", "content": "Search for the M5 iPad memory."},
                       {"role": "assistant", "content": "", "tool_calls": [{
                           "type": "function", "id": "call_1",
                           "function": {"name": "web_search",
                                        "arguments": {"query": "M5 iPad \"Pro\" memory", "count": 3}}}]},
                       {"role": "tool", "content": "RESULT_TEXT", "tool_call_id": "call_1", "name": "web_search"}],
                      TOOLS),
}


def render(source, messages, tools):
    return ENV.from_string(source).render(messages=messages, tools=tools, documents=None,
                                          add_generation_prompt=True, bos_token="<BOS>", eos_token="<EOS>")


def swift_literal(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7F:
            out.append("\\u{%x}" % code)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def identifier(name):
    parts = re.split(r"[^A-Za-z0-9]+", name)
    head, tail = parts[0].lower(), "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return head + tail


def main(headers_dir, output):
    templates = sorted(Path(headers_dir).glob("*.jinja"))
    if not templates:
        sys.exit(f"No .jinja files in {headers_dir}")
    lines = [
        "// Generated by scripts/generate-template-fixtures.py. Do not edit.",
        "//",
        "// Each catalog model's chat template (its GGUF `tokenizer.chat_template`) and the text Hugging Face",
        "// Transformers' renderer produces for three conversations. The templates belong to their model",
        "// authors; they're included only to test compatibility.",
        "",
        "import Testing",
        "",
        "struct TemplateFixture: Sendable, CustomTestStringConvertible {",
        "    let model: String",
        "    let template: String",
        "    let expected: [String: String]",
        "    var testDescription: String { model }",
        "}",
        "",
        "enum TemplateFixtures {",
        "    static let all: [TemplateFixture] = [" + ", ".join(identifier(p.stem) for p in templates) + "]",
    ]
    for path in templates:
        source = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        expected = {}
        for name, (messages, tools) in SCENARIOS.items():
            expected[name] = render(source, messages, tools)
        entries = ", ".join(f"{swift_literal(k)}: {swift_literal(v)}" for k, v in expected.items())
        lines.append("")
        lines.append(f"    static let {identifier(path.stem)} = TemplateFixture(")
        lines.append(f"        model: {swift_literal(path.stem)},")
        lines.append(f"        template: {swift_literal(source)},")
        lines.append(f"        expected: [{entries}]")
        lines.append("    )")
    lines.append("}")
    lines.append("")
    Path(output).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {len(templates)} fixtures to {output}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
